logger = get_logger(__name__)

#: Stable ledger identity (#178).
JOB_SLUG = "parity-spans"

#: The SOS legislative-results store — the ballot that positions a House seat.
SOS_SOURCE = "usa_wa_sos_results"

#: Every span kind the conformed tier owns — all four since #309 increment 3
#: brought `chamber-house` (the WSL roster x SOS ballot join).
OWNED_KINDS = ("party", "chamber-senate", "committee", "chamber-house")

#: Known stale-oracle rows, measured 2026-09-03 (see the module docstring):
#: 42 + 37 missing (WSL shallow keys and their roster-minted twins, one
#: pre-#277 identity split each), 2 extra, 1 dated. Lower this the moment a
#: Postgres-tier rebuild lands — the number dying is the point.
BASELINE_DIVERGENCE = 82

#: The role dimension's own ratchet, measured 2026-09-03: **0** — 312 conformed
#: role keys against 312 in ``canonical.roles``, exact in both directions, with
#: matching ``role_type``s. Roles are far coarser than tenures (312 slots vs
#: 8,849 spans), so the pre-#277 identity splits that make
#: :data:`BASELINE_DIVERGENCE` nonzero do not change *which slots exist*. It is
#: a ratchet rather than an invariant for the same reason the span one is — the
#: oracle is a snapshot — but it starts where that one is going.
ROLE_BASELINE_DIVERGENCE = 0

#: Counters that must be ZERO, checked together (CR 72/73/78). Unlike
#: ``divergence`` these carry no known-stale story — each is a defect in an
#: input or in the identity join, and each is 0 on the live corpus today. They
#: are *gated*, not merely reported, because the nightly's ``OnFailure=``
#: alerting fires on the exit code: a counter that only reaches journald tells
#: nobody, which is the silence findings 60 and 68 were about.
INTEGRITY_COUNTERS = (
    "unregistered_spans",
    "unregistered_orgs",
    "malformed_roster_rows",
    "unparsable_canonical_keys",
)


def _add_args(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--root", default=None, help="Raw store root (default USA_WA_RAW_ROOT).")
    parser.add_argument(
        "--baseline",
        type=int,
        default=BASELINE_DIVERGENCE,
        help="Max tolerated divergence from the (stale) canonical snapshot.",
    )
    parser.add_argument(
        "--role-baseline",
        type=int,
        default=ROLE_BASELINE_DIVERGENCE,
        help="Max tolerated divergence between the derived role keys and canonical.roles.",
    )


def owned_kind(source_id: str) -> str | None:
    """The span ``kind`` encoded in an assignment's ``source_id``, or ``None``.

    A span key is ``<member_id>:<kind>:<discriminator>:<start_biennium>`` — but
    the **member id is not colon-free**: the roster family mints ``<fold>:<year>``
    ids, so its keys carry five segments and counting from the left lands on the
    mint year (CR 58). Only the last three parts are structural, so the read is
    right-anchored. A key too short to carry one returns ``None`` — a probe
    degrades on a malformed row rather than crashing the nightly chain.
    """
    parts = source_id.rsplit(":", 3)
    return parts[1] if len(parts) == 4 else None


async def run_parity(
    session: AsyncSession,
    store: RawStore,
    roster_store: RawStore,
    sos_store: RawStore,
    *,
    baseline: int,
    current_biennium: str,
    role_baseline: int = ROLE_BASELINE_DIVERGENCE,
    sponsor_rows: Callable[[RawStore], list[dict[str, Any]]] = wsl.sponsor_rows,
    committee_member_rows: Callable[[RawStore], list[dict[str, Any]]] = wsl.committee_member_rows,
    roster_rows: Callable[[RawStore], list[dict[str, Any]]] = roster_staging.roster_rows,
    sos_result_rows: Callable[[RawStore], list[dict[str, Any]]] = sos_staging.result_rows,
) -> JobResult:
    """Diff the rebuilt spans against the canonical snapshot. Write-free.

    The staging readers are injected so the comparator and its exit gate are
    testable without a raw corpus (the shape :mod:`parity_wsl` uses).
    """
    if not store.latest():
        logger.warning("parity_spans_empty_store", extra={"source": SOURCE})
        return JobResult.degraded({"empty_store": True})
    if not roster_store.latest():
        # Without it the #228 deepening is lost and divergence explodes — which
        # would read as a regression in the port rather than a missing input.
        logger.warning("parity_spans_empty_roster_store", extra={"source": ROSTER_SOURCE})
        return JobResult.degraded({"empty_roster_store": True})

    # The guard belongs on the ROWS, not the store (CR 69): a store holding
    # wires that yield nothing must degrade with a named reason here, rather
    # than raising out of build_all_spans through the harness's exception
    # route — which loses the counters (#331).
    roster = roster_rows(roster_store)
    if not roster:
        logger.warning("parity_spans_empty_roster_rows", extra={"source": ROSTER_SOURCE})
        return JobResult.degraded({"empty_roster_rows": True})
    # PARTIAL malformation trips neither the CR-67 raise (records survive) nor
    # anything else — it quietly degrades the #228 deepening (CR 73). The build
    # re-parses; this parse is cheap and makes the number a gated counter
    # rather than a log line in a job whose logs nobody reads while it passes.
    malformed_roster_rows = len(roster) - len(roster_records(roster))

    sponsors = sponsor_rows(store)
    sos_results = sos_result_rows(sos_store)
    if sponsors and not sos_results:
        # The House family's ballot input, guarded like the roster tier's:
        # its absence deletes ~4% of the table, inside the publish shrink floor.
        logger.warning("parity_spans_empty_sos_rows", extra={"source": SOS_SOURCE})
        return JobResult.degraded({"empty_sos_rows": True})
    events = await operator_event_rows(session)
    # One resolve, both families — see `conformed.spans.roster_resolution`.
    resolution = roster_resolution(roster, sponsors)
    spans = build_all_spans(
        SpanInputs(
            sponsors=sponsors,
            committee_members=committee_member_rows(store),
            roster=roster,
            sos_results=sos_results,
            events=events,
        ),
        current_biennium=current_biennium,
        extra_observations=resolution.joined,
    )
    roster_spans = build_roster_spans(
        resolution, events=events, current_biennium=current_biennium, context_spans=spans
    )
    families = {SOURCE: spans, ROSTER_SOURCE: roster_spans}

    # Keyed by (source, source_id): the two families are disjoint identity
    # spaces sharing one table, and only the pair is unique by construction.
    ours = {
        (source, s.source_id): (s.valid_from, s.valid_to, s.is_active)
        for source, family in families.items()
        for s in family
    }
    canonical: dict[tuple[str, str], tuple[Any, Any, Any]] = {}
    unparsable = 0
    for row in (
        await session.execute(
            select(
                Assignment.source,
                Assignment.source_id,
                Assignment.valid_from,
                Assignment.valid_to,
                Assignment.is_active,
            ).where(Assignment.source.in_(tuple(families)))
        )
    ).all():
        kind = owned_kind(row[1])
        if kind is None:
            # Excluding a key that cannot carry a kind is right; excluding it
            # SILENTLY shrinks the oracle unnoticed (CR 70).
            unparsable += 1
        elif kind in OWNED_KINDS:
            canonical[(row[0], row[1])] = (row[2], row[3], row[4])
    if not canonical:
        # An empty oracle makes every comparison vacuously clean (#302 CR 6).
        logger.warning("parity_spans_empty_canonical", extra={"sources": sorted(families)})
        return JobResult.degraded({"empty_canonical": True, "spans": len(ours)})

    # The crosswalk join the `assignments` model performs, reported HERE
    # because the model cannot report it (CR 68): a `dbt build` never calls
    # `configure_logging`, so a logger inside a Python model emits nothing —
    # the info path is dropped outright and the warning path reaches
    # `logging.lastResort`, which prints the message and discards `extra`.
    # This probe runs under the job harness, so its counters are real JSON.
    #
    # NOT the same read the model made (CR 75): the nightly runs
    # `dbt build → registrar → publish → parity`, so the registrar may have
    # bound keys since. This measures the registry as it stands NOW — which is
    # the state tomorrow's build will publish from, so a gap here is the one
    # worth alarming on. A gap the registrar has since closed is transient and
    # self-healing, and correctly reads as zero.
    _rows, join = assignment_rows(
        families, entity_index(await crosswalk_rows(session, KIND_PERSON))
    )

    # The ROLE dimension, against the tier that already publishes these keys to
    # Power Map (CR 77). The dbt `assignments_name_a_role` test cannot catch a
    # fork: `roles` is generated by iterating `assignments` through the same
    # `role_for_span`, so containment holds by construction.
    #
    # Derived from the SPANS, not from `_rows`: a slot exists whether or not the
    # person filling it is registered, so reading the crosswalk-joined rows
    # would let a registrar gap shrink the role dimension too — one defect
    # masking another. `unregistered_orgs` is the roles model's own discarded
    # counter (CR 78), which a Python model cannot report for the reason below.
    derived_roles, role_join = role_rows(
        [
            {"span_kind": s.kind, "span_discriminator": s.discriminator}
            for family in families.values()
            for s in family
        ],
        entity_index(await crosswalk_rows(session, KIND_ORG)),
    )
    our_role_keys = {row["role_key"] for row in derived_roles}
    canonical_role_keys = {
        row[0]
        for row in (
            await session.execute(
                select(CanonicalRole.source_id).where(
                    CanonicalRole.source == ROLE_SOURCE,
                    CanonicalRole.deleted_at.is_(None),
                )
            )
        ).all()
    }
    if not canonical_role_keys:
        # Same rule as the empty span oracle: report "no oracle", never a fork.
        logger.warning("parity_spans_empty_canonical_roles", extra={"source": ROLE_SOURCE})
        return JobResult.degraded({"empty_canonical_roles": True, "roles": len(our_role_keys)})
    role_only_ours = sorted(our_role_keys - canonical_role_keys)
    role_only_canonical = sorted(canonical_role_keys - our_role_keys)

    missing = sorted(set(canonical) - set(ours))
    extra = sorted(set(ours) - set(canonical))
    dated = sorted(k for k in set(ours) & set(canonical) if ours[k] != canonical[k])
    divergence = len(missing) + len(extra) + len(dated)
    counters = {
        "spans": len(ours),
        "wsl_spans": len(spans),
        "roster_spans": len(roster_spans),
        "canonical": len(canonical),
        "missing": len(missing),
        "extra": len(extra),
        "dated_differently": len(dated),
        "divergence": divergence,
        "baseline": baseline,
        "registered_spans": join["published"],
        "unregistered_spans": join["unregistered_spans"],
        "malformed_roster_rows": malformed_roster_rows,
        "unparsable_canonical_keys": unparsable,
        "roles": len(our_role_keys),
        "canonical_roles": len(canonical_role_keys),
        "role_divergence": len(role_only_ours) + len(role_only_canonical),
        "role_baseline": role_baseline,
        "unregistered_orgs": role_join["unregistered_orgs"],
    }
    counters["integrity_failures"] = [c for c in INTEGRITY_COUNTERS if counters[c]]
    clean = (
        divergence <= baseline
        and counters["role_divergence"] <= role_baseline
        and not counters["integrity_failures"]
    )
    log = logger.info if clean else logger.error
    log(
        "parity_spans_report",
        extra={
            "summary": counters,
            "missing_sample": [f"{src}/{sid}" for src, sid in missing[:20]],
            "extra_sample": [f"{src}/{sid}" for src, sid in extra[:20]],
            "dated_sample": [f"{src}/{sid}" for src, sid in dated[:20]],
            "role_only_ours_sample": role_only_ours[:20],
            "role_only_canonical_sample": role_only_canonical[:20],
        },
    )
    if not clean:
        return JobResult.failed(counters, exit_code=1)
    return JobResult.ok(counters)


async def _parity_job(ctx: JobContext) -> JobResult:
    """Bind the probe to the real raw root and the current biennium."""
    root = Path(ctx.args.root) if ctx.args.root else get_raw_root()
    return await run_parity(
        ctx.require_session(),
        RawStore(root, SOURCE),
        RawStore(root, ROSTER_SOURCE),
        RawStore(root, SOS_SOURCE),
        baseline=ctx.args.baseline,
        role_baseline=ctx.args.role_baseline,
        current_biennium=(
            os.environ.get("USA_WA_BIENNIUM") or biennium_for_date(datetime.now(UTC).date())
        ),
    )


def main(argv: list[str] | None = None) -> int:
    """Diff conformed spans against the canonical assignment snapshot."""
    return run_job(
        JOB_SLUG,
        _parity_job,
        argv=argv,
        prog="python -m usa_wa_pipeline.parity_spans",
        description="Write-free parity: conformed tenure spans vs canonical assignments (#309).",
        extra_args=_add_args,
        commit=False,
        dry_run=False,
    )


if __name__ == "__main__":
    raise SystemExit(main())
