"""Span parity probe (#309): conformed spans vs. canonical assignments.

    python -m usa_wa_pipeline.parity_spans [--root PATH] [--baseline N] [--json]

Write-free. Rebuilds the conformed spans from the raw store + the curated
operator events and diffs them against ``canonical.assignments`` for all four
kinds this tier owns (:data:`OWNED_KINDS` — ``party``, ``chamber-senate``,
``committee`` and, since #309 increment 3, ``chamber-house``), keyed on the
span's 4-part identity with ``valid_from``/``valid_to``/``is_active`` compared
exactly.

It also diffs the **role dimension** those spans name against
``canonical.roles`` (CR 77). The dbt ``assignments_name_a_role`` test cannot do
this: ``roles`` is generated by iterating ``assignments`` through the same
``role_for_span``, so containment holds by construction and the query is
unfalsifiable. The fork worth detecting is ours drifting from the tier that
already publishes these keys to Power Map, and only a probe with a session can
see it.

Both families are rebuilt and diffed: the WSL archive's (numeric member ids)
and the roster PDF's (minted ``<fold>:<year>`` identities). They share the
table but not the identity space, so the comparison key is
``(source, source_id)``.

**The oracle is a snapshot, and it is stale.** Measured 2026-09-03: the stored
assignments diverge from the port by :data:`BASELINE_DIVERGENCE` rows — and
running the *Postgres-tier adapter's own pipeline* fresh that day produced the
**identical** divergence for the WSL family (4,851 spans; 42 missing / 2 extra
/ 1 dated differently), because the stored rows predate the current
identity-resolve (the #277/#281 candidate-splitting work).

The roster family adds **37 missing rows across 15 identities, the same story
seen from the other side**: each is an identity the stored snapshot minted as a
roster person and today's resolve JOINS to a WSL member. Cliff Bailey is the
worked example — canonical holds both a shallow ``15:*:1991-92`` pair *and* a
minted ``cliffbailey:1985:*`` pair, where this build asserts the one merged
``15:*:1985-86`` tenure the #228 deepening produces. Nothing is lost; the
tenure moved families, which is exactly what the #97 collapse is for.

So this probe's gate is a **ratchet, not equality**: divergence at or below the
recorded baseline is the known staleness, and any growth is a regression in
the port. A Postgres-tier span rebuild would drop the baseline to zero, at
which point lower it here — the number dying is the point.

Four integrity counters (``unregistered_spans``, ``unregistered_orgs``,
``malformed_roster_rows``, ``unparsable_canonical_keys``) carry no known-stale
story and must be ZERO; unlike the divergence ratchets they are gated, because
the nightly alerts on the exit code and a counter that only reaches journald
tells nobody (CR 72/73/78).

Exit ``0`` clean · ``1`` either divergence past its baseline OR any integrity
counter nonzero · ``4`` degraded — no WSL store, no roster store or roster rows
(the #228 deepening's input, whose absence would read as a port regression), or
an empty oracle on either side. A degraded probe compared nothing and says so.
"""

