"""``.github/dependabot.yml`` is the update mechanism for ``uv.lock`` (#499).

Owner's decision (2026-10-15): Dependabot monthly, one grouped PR, landed in the
patching-hosts window (``.skills/patching-hosts``) next to the OS run; the
report-only ``scripts/audit-lock.sh`` shows a disclosure between runs. A
mistyped Dependabot config stops producing PRs without erroring anywhere a
person looks, so each property is pinned here. CannObserv/broker's and
CannObserv/notifier's ``test_dependabot.py`` are the templates.

* **``uv`` only, at ``/``.** The workspace's one ``uv.lock`` sits at the root.
  ``github-actions`` is out: the only workflow is ``context-cadence.yml``, which
  ``install-cadence.sh`` regenerates, reverting any bump made in it.
* **Monthly, one group over everything**, so each month brings one PR.
* **``increase-if-necessary``.** The members are packages with a build backend;
  ``auto`` resolves to ``widen`` for libraries, unsupported for uv
  (dependabot-core#15290, notifier#33).
* **The commit prefix is one of AGENTS.md's types.**
* **No workspace dependency declares extras.** The uv updater gives a
  ``name[extra]`` requirement no previous version and then discards the whole
  grouped PR, green and silent (dependabot-core#16431): #499's first run did
  exactly that on ``sqlalchemy[asyncio]``. Spell the extra's own requirements
  out instead.
"""

from __future__ import annotations

import re
import tomllib
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
CONFIG = REPO / ".github" / "dependabot.yml"
AGENTS = REPO / "AGENTS.md"
CADENCE = REPO / ".github" / "workflows" / "context-cadence.yml"
EXTRAS = re.compile(r"^\s*[A-Za-z0-9][A-Za-z0-9._-]*\s*\[")


def _config() -> dict:
    return yaml.safe_load(CONFIG.read_text()) if CONFIG.is_file() else {}


def _block() -> dict:
    updates = _config().get("updates") or []
    assert len(updates) == 1, f"expected one update block, found {len(updates)}"
    return updates[0]


def test_config_exists():
    assert CONFIG.is_file(), "no .github/dependabot.yml: nothing moves uv.lock (#499)"


def test_config_is_version_2():
    """A version 1 config is ignored without an error."""
    assert _config().get("version") == 2


def test_only_uv_is_configured():
    assert _block()["package-ecosystem"] == "uv"


def test_github_actions_stays_out_while_the_only_workflow_is_generated():
    """Revisit if a hand-written workflow lands beside context-cadence.yml."""
    workflows = sorted(p.name for p in CADENCE.parent.glob("*.y*ml"))
    assert workflows == ["context-cadence.yml"], workflows
    assert "Generated by" in CADENCE.read_text()


def test_it_reads_the_workspace_root_lock():
    """``/`` is where ``uv.lock`` lives; any other directory is silence."""
    block = _block()
    assert block.get("directory") == "/"
    assert "directories" not in block
    assert (REPO / "uv.lock").is_file()


def test_it_runs_monthly():
    assert _block()["schedule"]["interval"] == "monthly"


def test_one_group_covers_every_dependency():
    """One PR a month, not one per package."""
    groups = _block().get("groups") or {}
    assert len(groups) == 1, groups
    (group,) = groups.values()
    assert group.get("patterns") == ["*"], group
    assert not group.get("exclude-patterns"), group
    assert "dependency-type" not in group, "a dependency-type would split the month's PR"


def test_strategy_is_not_the_unsupported_widen():
    assert _block().get("versioning-strategy") == "increase-if-necessary"


def test_the_commit_prefix_is_one_of_agents_md_types():
    types = re.search(r"^Types: (.*)$", AGENTS.read_text(), re.MULTILINE)
    assert types, "AGENTS.md lost its `Types:` line"
    assert _block()["commit-message"]["prefix"] in types.group(1).split(", ")


def _requirements(pyproject: Path) -> list[str]:
    """Every requirement string a pyproject declares: dependencies, optional
    dependencies and dependency groups (``{include-group}`` tables skipped)."""
    data = tomllib.loads(pyproject.read_text())
    project = data.get("project", {})
    reqs = list(project.get("dependencies", []))
    for group in project.get("optional-dependencies", {}).values():
        reqs += group
    for group in data.get("dependency-groups", {}).values():
        reqs += [r for r in group if isinstance(r, str)]
    return reqs


def test_no_workspace_dependency_declares_extras():
    pyprojects = [REPO / "pyproject.toml", *sorted(REPO.glob("packages/*/pyproject.toml"))]
    assert len(pyprojects) > 1, "found no workspace members - the glob broke"
    bad = [
        f"{p.relative_to(REPO)}: {r}"
        for p in pyprojects
        for r in _requirements(p)
        if EXTRAS.match(r)
    ]
    assert not bad, (
        "a dependency with extras makes Dependabot drop the whole monthly PR "
        "(dependabot-core#16431); declare the extra's requirements directly:\n  " + "\n  ".join(bad)
    )


def test_the_extras_check_sees_an_extra():
    assert EXTRAS.match("sqlalchemy[asyncio]>=2.0,<3")
    assert EXTRAS.match("uvicorn [standard]")
    assert not EXTRAS.match("sqlalchemy>=2.0,<3")
    assert not EXTRAS.match('pycurl; platform_python_implementation != "PyPy"')
